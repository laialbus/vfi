//! Price/sales: market capitalisation, the unadjusted close at the valuation
//! date times the average of common shares outstanding at the instants a year
//! opens and closes at, over revenue for the year. Its form, its year, its
//! four conditions and how its absence composes are
//! `docs/adr/market-capitalisation-and-the-equity-multiples.md`'s, under the
//! method version.
//!
//! It is stated over a year, as
//! `docs/adr/which-duration-precedes-a-duration.md` defines one, so at a
//! duration that is not one it gives the year test's one reason and makes no
//! read. At a year it reads the count at the opening instant and then the
//! closing instant, then revenue at the year, and the close through the one
//! price read, E being the year's end, which is the date of the closing
//! instant: the share-basis rule is asked once and not per figure. Every read
//! is made and none stops another: the reads' reasons, if any, come first in
//! input order, and the price read's follows. Every year's multiple is that
//! year's revenue against the one close. It reads no setting.
//!
//! The numerator is formed in [`super::market_capitalisation`], at each
//! instant the count was read at and before the mean, so it is the mean of
//! the two terms. The product is not written here.
//!
//! Source of the form and the year: Damodaran, A., *Investment Valuation*,
//! 2nd ed., John Wiley and Sons, 2002, chapter 20, "Revenue Multiples and
//! Sector-Specific Multiples", read from the author's own copy of the
//! chapter, <https://pages.stern.nyu.edu/~adamodar/pdfiles/valn2ed/ch20.pdf>,
//! 42 pages whose printed numbers match their positions, 103,261 bytes,
//! sha256 `995b0d71d0a5b69322ae5ebcf3384fe6d8cb41accdb9abfd50be32546e61d246`.
//! Page 2: "The first, and more popular one, is the multiple of the market
//! value of equity to the revenues of a firm – this is termed the price to
//! sales ratio." The equation that follows is set as an object whose words
//! the page's text interleaves: the price to sales ratio is the market value
//! of equity over revenues. Page 4, for the revenue being a year's: "The
//! price to sales ratio for a stable firm can be extracted from a stable
//! growth dividend discount model.", whose terms the page defines one to a
//! line, "DPS1 = Expected dividends per share next year" and "r = Required
//! rate of return on equity". The record reads the form the ratio is
//! extracted from as setting a dividend next year against a return per year,
//! so the revenue is a year's.
//!
//! Beside it: Damodaran, A., *Valuation Approaches and Metrics: A Survey of
//! the Theory and Evidence*, Stern School of Business, New York University,
//! November 2006,
//! <https://pages.stern.nyu.edu/~adamodar/pdfiles/papers/valuesurvey.pdf>, 77
//! pages, 1,602,127 bytes, sha256
//! `9bb7f22c1a7a6b10e37421e126ff0c07b062425fe0b1f23d409516c3386897eb`. Page
//! 60: "the price/sales ratio (PS), where the market value of equity is
//! divided by the revenues generated by the firm".
//!
//! The averaged count is `docs/adr/which-other-period-a-metric-reads.md`'s
//! rule as written, "Every other metric that pairs a flow with a balance
//! reads the average", read as reaching a count the price multiplies. Its
//! cost is the record's to name: the averaged term is the market value at no
//! date, and where the count rose over the year it is understated, so the
//! multiple reads low, which flatters. The rule is asked with E at the
//! year's end and does not see the opening count: a split dated after the
//! opening instant and before E passes it, and the average then mixes two
//! share bases. The record leaves both open, each to a superseding record of
//! its own.
//!
//! What no check can see: leverage. The chapter's page 2: "The price to sales
//! ratio divides an equity value by revenues that are generated for the firm.
//! Consequently, it will yield lower values for more highly levered firms".
//! And the kind: for a `bank`, v2 reads `revenue` as a net figure, net
//! interest income together with non-interest income, so a bank's price/sales
//! does not compare with an operating filer's, which is set over a gross one.

use std::cmp::Ordering;

use vfi_contracts::analyze_store::Reasons;
use vfi_contracts::canonical_concepts::Concept;

use super::discounted_cash_flow_margin_of_safety::NON_POSITIVE_CLOSE;
use super::market_capitalisation::{NON_POSITIVE_SHARES_OUTSTANDING, market_capitalisation};
use super::reading::price::{SHARE_BASIS_DATE_NOT_A_DATE, beside_the_close};
use super::reading::year::{END_NOT_A_DATE, NOT_A_YEAR, OVERLAPS_ANOTHER_YEAR, year};
use super::reading::{Reading, reads};
use super::{Computing, Derivation, Entry, Shape, Unit, ZERO_REVENUE, declined};
use crate::arithmetic::Number;
use crate::date::START_NOT_A_DATE;

/// Revenue over the year is below zero. No source states the multiple at a
/// negative denominator. Page 1 of the chapter cited above says of the other
/// multiples: "unlike earnings and book value ratios, which can become
/// negative for many firms and thus not meaningful, revenue multiples are
/// available even for the most troubled firms and for very young firms." The
/// record applies "not meaningful" here as its own decision, for one rule
/// over four multiples: a negative multiple is a price for no unit of
/// revenue, and its sign is the denominator's and not the price's. Stored as
/// a figure it would sort below every real multiple.
const NEGATIVE_REVENUE: &str = "negative_revenue";

pub(super) const PRICE_TO_SALES: Derivation = Derivation {
    entry: Entry {
        name: "price_to_sales",
        meaning: "Market capitalisation, the unadjusted close at the valuation date times the \
                  average of common shares outstanding at the instants the year opens and closes \
                  at, over revenue for the year.",
        unit: Unit::Multiple,
        stated_at: Shape::Duration,
        inputs: &[Concept::SharesOutstanding, Concept::Revenue],
        conditions: &[
            NON_POSITIVE_CLOSE,
            NON_POSITIVE_SHARES_OUTSTANDING,
            ZERO_REVENUE,
            NEGATIVE_REVENUE,
            START_NOT_A_DATE,
            END_NOT_A_DATE,
            NOT_A_YEAR,
            OVERLAPS_ANOTHER_YEAR,
            SHARE_BASIS_DATE_NOT_A_DATE,
        ],
    },
    readings: &[Some(Reading::Averaged), None],
    derived: price_to_sales,
};

/// The year test, so that a year's price is the only one read, then the
/// reads and the price read side by side, then the term's two conditions,
/// then revenue's two, then the one division.
fn price_to_sales(computing: &Computing) -> Result<Number, Reasons> {
    year(computing).map_err(|reason| Reasons::of(reason, Vec::new()))?;
    let ([shares_outstanding, revenue], close) = beside_the_close(
        reads(computing, &PRICE_TO_SALES),
        computing.close_at_valuation_date(),
    )?;
    let market_capitalisation = market_capitalisation(&close, &shares_outstanding)?.mean();
    let revenue = revenue.mean();
    match revenue.sign() {
        Ordering::Equal => Err(declined(ZERO_REVENUE)),
        Ordering::Less => Err(declined(NEGATIVE_REVENUE)),
        Ordering::Greater => Ok(market_capitalisation
            .divided(&revenue)
            .expect("revenue is above zero")),
    }
}

#[cfg(test)]
mod tests {
    use vfi_contracts::canonical_concepts::Concept;

    use super::{NEGATIVE_REVENUE, PRICE_TO_SALES};
    use crate::arithmetic::INPUT_NOT_A_DECIMAL;
    use crate::date::START_NOT_A_DATE;
    use crate::metrics::discounted_cash_flow_margin_of_safety::NON_POSITIVE_CLOSE;
    use crate::metrics::market_capitalisation::NON_POSITIVE_SHARES_OUTSTANDING;
    use crate::metrics::reading::Reading;
    use crate::metrics::reading::price::SHARE_BASIS_DATE_NOT_A_DATE;
    use crate::metrics::reading::year::{END_NOT_A_DATE, NOT_A_YEAR, OVERLAPS_ANOTHER_YEAR};
    use crate::metrics::{DERIVATIONS, Shape, Unit, ZERO_REVENUE};

    #[test]
    fn the_entry_states_the_metric_once() {
        let entry = &PRICE_TO_SALES.entry;
        assert_eq!(entry.name, "price_to_sales");
        assert_eq!(
            entry.meaning,
            "Market capitalisation, the unadjusted close at the valuation date times the average \
             of common shares outstanding at the instants the year opens and closes at, over \
             revenue for the year."
        );
        assert_eq!(entry.unit, Unit::Multiple);
        assert_eq!(entry.stated_at, Shape::Duration);
        assert_eq!(entry.inputs, [Concept::SharesOutstanding, Concept::Revenue]);
        assert_eq!(PRICE_TO_SALES.readings, [Some(Reading::Averaged), None]);
        assert_eq!(
            entry.declined().collect::<Vec<_>>(),
            [
                "non_positive_close",
                "non_positive_shares_outstanding",
                "zero_revenue",
                "negative_revenue",
                "start_not_a_date",
                "end_not_a_date",
                "not_a_year",
                "overlaps_another_year",
                "share_basis_date_not_a_date",
                INPUT_NOT_A_DECIMAL
            ]
        );
    }

    #[test]
    fn each_condition_it_reaches_is_listed_by_its_one_constant() {
        assert_eq!(
            PRICE_TO_SALES.entry.conditions,
            [
                NON_POSITIVE_CLOSE,
                NON_POSITIVE_SHARES_OUTSTANDING,
                ZERO_REVENUE,
                NEGATIVE_REVENUE,
                START_NOT_A_DATE,
                END_NOT_A_DATE,
                NOT_A_YEAR,
                OVERLAPS_ANOTHER_YEAR,
                SHARE_BASIS_DATE_NOT_A_DATE,
            ]
        );
    }

    #[test]
    fn its_name_says_neither_common_nor_per_share_and_its_meaning_says_common_shares() {
        let entry = &PRICE_TO_SALES.entry;
        assert!(!entry.name.contains("common"));
        assert!(!entry.name.contains("per_share"));
        assert!(entry.meaning.contains("common shares outstanding"));
        for unread in [
            Concept::DilutedSharesWeightedAverage,
            Concept::NetIncome,
            Concept::EarningsPerShareDiluted,
        ] {
            assert!(!entry.inputs.contains(&unread), "{unread:?}");
        }
    }

    #[test]
    fn the_hand_over_carries_the_entrys_name_once() {
        let named = DERIVATIONS
            .iter()
            .filter(|derivation| derivation.entry.name == PRICE_TO_SALES.entry.name)
            .count();
        assert_eq!(named, 1);
    }
}
